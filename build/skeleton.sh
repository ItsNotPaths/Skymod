#!/usr/bin/env bash
# Regenerate docs/skeleton.md from HOLE() markers in the source.
#
# A HOLE marks something that is reachable but does not work yet: a stub, a missing
# subsystem, a decoder nothing calls. The map is GENERATED so it cannot drift from the
# code — never edit docs/skeleton.md by hand.
#
#   // HOLE(<system>): one line, terse.
#   // HOLE(<system>, <severity>): the same, with an explicit severity.
#
# Severity defaults to `gap` and only orders holes WITHIN a section. The sections
# themselves carry no order — `graphics` is not ahead of or behind `audio`.
#
# Both vocabularies are closed. An unknown system or severity fails the build, because an
# open vocabulary becomes forty tags in a month.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
OUT="docs/skeleton.md"

# Section order below is presentation only — related systems sit next to each other so the
# doc reads top to bottom. It is NOT a priority ranking and nothing should read it as one.
SYSTEMS=(script records save world render assets physics animation ai combat dialogue magic vfx audio ui input mods)

declare -A BRIEF=(
    [script]="Papyrus conversion and the native surface. The rewrite program (docs/script-rewrite.md) starts here."
    [records]="ESM/ESP parsing and the baseline form database everything else reads through."
    [save]="Durable state: what persists, who owns it, what survives a reload."
    [world]="Cells, streaming, traversal and the live instance scene."
    [render]="Graphics: the frame, materials, lighting and everything drawn."
    [assets]="Meshes, textures and the caches that hold them."
    [physics]="Jolt wrapper, bodies, the character controller and spatial queries."
    [animation]="Skeletons, clips and anything that moves a mesh over time."
    [ai]="Actors as agents: packages, schedules, navigation, perception."
    [combat]="Hostility, damage, death and the rules between them."
    [dialogue]="Conversation trees, topics, voice and the menus around them."
    [magic]="Spells, effects and the machinery that applies them to actors."
    [vfx]="Effect shaders, particles and screen-space effects."
    [audio]="Sound playback, categories, music and ambience."
    [ui]="Menus, HUD and the Lua UI substrate."
    [input]="Devices, bindings and prompts."
    [mods]="Load order, the VFS, installation and conflict resolution."
)

SEVERITIES=(blocker gap polish)
declare -A SEV_LABEL=(
    [blocker]="Blocking — the system cannot work at all until this lands"
    [gap]="Gap — reachable and wrong, or only partly built"
    [polish]="Polish — correctness or cost debt behind something that already works"
)

in_list() {
    local needle="$1"; shift
    local x
    for x in "$@"; do [ "$x" = "$needle" ] && return 0; done
    return 1
}

# file<TAB>line<TAB>system<TAB>severity<TAB>text
rows="$(grep -rnP '(//|--)\s*HOLE\(' --include='*.odin' --include='*.lua' --include='*.sh' \
        src tools build 2>/dev/null | grep -v '^build/skeleton.sh:' \
    | perl -ne 'next unless /^([^:]+):(\d+):.*?(?:\/\/|--)\s*HOLE\(\s*(\w+)\s*(?:,\s*(\w+)\s*)?\):\s*(.*?)\s*$/;
                printf "%s\t%s\t%s\t%s\t%s\n", $1, $2, $3, ($4 // "gap"), $5' || true)"

bad=0
while IFS=$'\t' read -r file line sys sev text; do
    [ -z "${file:-}" ] && continue
    if ! in_list "$sys" "${SYSTEMS[@]}"; then
        echo "  $file:$line: unknown HOLE system '$sys' (add it to SYSTEMS in build/skeleton.sh, or fix the marker)" >&2
        bad=1
    fi
    if ! in_list "$sev" "${SEVERITIES[@]}"; then
        echo "  $file:$line: unknown HOLE severity '$sev' (one of: ${SEVERITIES[*]})" >&2
        bad=1
    fi
    if [ -z "$text" ]; then
        echo "  $file:$line: HOLE marker has no text" >&2
        bad=1
    fi
done <<< "$rows"
[ "$bad" -eq 1 ] && exit 1

total="$(printf '%s' "$rows" | grep -c . || true)"
n_sys="$(printf '%s' "$rows" | cut -f3 | sort -u | grep -c . || true)"

{
    echo "# Architecture skeleton"
    echo
    echo "Every reachable thing that does not work yet. GENERATED by \`build/skeleton.sh\` from"
    echo "\`HOLE(system)\` markers in the source — do not edit this file."
    echo
    echo "A hole is not a bug and not a wish. It is a symbol something can already call, which"
    echo "returns a default or does nothing, because the system behind it is not built. Grep"
    echo "\`HOLE(\` to find them all; \`grep 'HOLE(audio'\` is the work list for one system."
    echo
    echo "**$total holes** across $n_sys systems. Holes are ordered within a section:"
    echo
    for s in "${SEVERITIES[@]}"; do echo "- **$s** — ${SEV_LABEL[$s]}"; done
    echo
    echo "The sections carry no order. Nothing here says graphics comes before audio."
    echo

    for sys in "${SYSTEMS[@]}"; do
        sec="$(printf '%s\n' "$rows" | awk -F'\t' -v s="$sys" '$3==s')"
        n="$(printf '%s' "$sec" | grep -c . || true)"
        [ "$n" -eq 0 ] && continue
        echo "## $sys ($n)"
        echo
        [ -n "${BRIEF[$sys]:-}" ] && { echo "${BRIEF[$sys]}"; echo; }
        for sev in "${SEVERITIES[@]}"; do
            part="$(printf '%s\n' "$sec" | awk -F'\t' -v v="$sev" '$4==v')"
            m="$(printf '%s' "$part" | grep -c . || true)"
            [ "$m" -eq 0 ] && continue
            echo "### $sev ($m)"
            echo
            printf '%s\n' "$part" | while IFS=$'\t' read -r file line _ _ text; do
                [ -z "${file:-}" ] && continue
                echo "- \`$file:$line\` — $text"
            done
            echo
        done
    done
} > "$OUT"

echo "  $total holes across $n_sys systems -> $OUT"
